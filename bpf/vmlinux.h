#ifndef SEC
#define SEC(name) \
	_Pragma("GCC diagnostic push") \
	_Pragma("GCC diagnostic ignored \"-Wignored-attributes\"") \
	__attribute__((section(name), used)) \
	_Pragma("GCC diagnostic pop")
#endif

